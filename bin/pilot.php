<?php

declare(strict_types=1);

/**
 * W13 pilot rehearsal: run one dinner service against a disposable copy of the
 * demo restaurant and print the service report plus the invariants.
 *
 *   php bin/pilot.php                       # in-memory demo, pilot date 2026-12-16
 *   php bin/pilot.php --db=/tmp/pilot.sqlite --backup=/tmp/pilot-backup.sqlite
 *   php bin/pilot.php --report=docs/pilot-record.md
 *
 * Exit code 1 means at least one invariant failed (no double booking, report
 * consistency, floor-plan consistency, backup restore, ...).
 */

require dirname(__DIR__) . '/bootstrap/autoload.php';

use DineReserve\Database;
use DineReserve\PilotService;

$root = dirname(__DIR__);
$options = ['db' => null, 'date' => PilotService::PILOT_DATE, 'backup' => null, 'report' => null];

foreach (array_slice($argv, 1) as $argument) {
    if (preg_match('/^--(db|date|backup|report)=(.*)$/', $argument, $match) === 1) {
        $options[$match[1]] = $match[2];
    }
}

$path = $options['db'] ?? sys_get_temp_dir() . '/dinereserve-pilot-' . date('YmdHis') . '.sqlite';
if ($path !== ':memory:' && is_file($path)) {
    unlink($path);
}
$pdo = Database::sqlite($path);
Database::migrate($pdo);
$seed = Database::seedDemo($pdo, 60);

$pilot = new PilotService($pdo);
$started = hrtime(true);
$result = $pilot->run((string) $options['date'], (int) $seed['restaurant_id'], $options['backup'] !== null ? (string) $options['backup'] : null);
$elapsed = (hrtime(true) - $started) / 1e6;

$summary = $result['summary'];
printf("Pilot service — %s (simulated in %.0f ms)\n\n", $summary['date'], $elapsed);
printf("Bookings created      %d\n", $summary['bookings_created']);
printf("Cancelled             %d\n", $summary['cancelled']);
printf("Waitlist entries      %d (offers %d)\n", $summary['waitlist_entries'], $summary['offers']);
printf("Covers served         %d\n", $summary['covers']);
printf("Utilisation           %.1f%%\n", $summary['utilisation_pct']);
printf("No-show rate          %.1f%%\n", $summary['no_show_rate_pct']);
printf("Channels              online=%d phone=%d walk_in=%d waitlist=%d\n",
    $summary['channels']['online'],
    $summary['channels']['phone'],
    $summary['channels']['walk_in'],
    $summary['channels']['waitlist']
);
printf("Notifications         sent=%d failed=%d queued=%d cancelled=%d\n",
    $summary['notifications']['sent'],
    $summary['notifications']['failed'],
    $summary['notifications']['queued'],
    $summary['notifications']['cancelled']
);
printf("Floor plan            %s\n\n", json_encode($summary['floor_plan'], JSON_UNESCAPED_SLASHES));

$failures = 0;
foreach ($result['invariants'] as $invariant) {
    printf("%s  %-44s %s\n", $invariant['ok'] ? 'PASS' : 'FAIL', $invariant['name'], $invariant['detail']);
    if (!$invariant['ok']) {
        $failures++;
    }
}

if ($options['report'] !== null) {
    $lines = [
        '# Pilot service record — ' . $summary['date'],
        '',
        '> Generated by `php bin/pilot.php` on ' . date('Y-m-d H:i') . '. The rehearsal runs the real',
        '> engine (availability, booking, waitlist, notifications, floor plan, reporting) against a',
        '> disposable copy of the demo restaurant and freezes the clock so the run is repeatable.',
        '',
        '## Service numbers',
        '',
        '| Metric | Value |',
        '|---|---|',
        '| Bookings created | ' . $summary['bookings_created'] . ' |',
        '| Cancelled | ' . $summary['cancelled'] . ' |',
        '| Waitlist entries / offers | ' . $summary['waitlist_entries'] . ' / ' . $summary['offers'] . ' |',
        '| Covers served | ' . $summary['covers'] . ' |',
        '| Utilisation | ' . sprintf('%.1f%%', $summary['utilisation_pct']) . ' |',
        '| No-show rate | ' . sprintf('%.1f%%', $summary['no_show_rate_pct']) . ' |',
        '| Channels | online ' . $summary['channels']['online'] . ' · phone ' . $summary['channels']['phone']
            . ' · walk-in ' . $summary['channels']['walk_in'] . ' · waitlist ' . $summary['channels']['waitlist'] . ' |',
        '| Notifications | sent ' . $summary['notifications']['sent'] . ' · failed ' . $summary['notifications']['failed']
            . ' · queued ' . $summary['notifications']['queued'] . ' · cancelled ' . $summary['notifications']['cancelled'] . ' |',
        '',
        '## Invariants',
        '',
        '| Check | Result | Detail |',
        '|---|---|---|',
    ];
    foreach ($result['invariants'] as $invariant) {
        $lines[] = '| ' . $invariant['name'] . ' | ' . ($invariant['ok'] ? 'PASS' : 'FAIL') . ' | ' . $invariant['detail'] . ' |';
    }
    $lines[] = '';
    $file = (string) $options['report'];
    if (!is_dir(dirname($file))) {
        mkdir(dirname($file), 0775, true);
    }
    file_put_contents($file, implode("\n", $lines) . "\n");
    printf("\nPilot record written to %s\n", $file);
}

if ($path !== ':memory:') {
    @unlink($path);
}

if ($failures > 0) {
    fwrite(STDERR, "\n{$failures} pilot invariant(s) failed.\n");
    exit(1);
}
echo "\nPilot rehearsal passed: the service ran clean.\n";
